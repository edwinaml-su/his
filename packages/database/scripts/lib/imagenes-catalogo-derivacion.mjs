// ---------------------------------------------------------------------------
// Reglas de derivación (mockup RE_CONTRASTE / RE_AYUNO / PREF / dur / autoriz)
// ---------------------------------------------------------------------------
export const RE_CONTRASTE =
  /ANGIO|CONTRASTE|UROGRAFIA|UROTOMOGRAFIA|COLANGIO|ENEMA|ESOFAGOGRAMA|TRANSITO|PIELOGRAMA|PIELOTAC|ARTERIOGRAFIA|FLEBOGRAFIA|VENOGRAFIA|FISTULOGRAMA|ARTROGRAMA|CISTOURETROGRAMA|URETROGRAMA|QUIMIOEMBOLIZACION|CORONARIA|MIELOTAC|TUBO DIGESTIVO/;
export const RE_AYUNO =
  /ABDOMEN|ABDOMINAL|HIGADO|VIAS BILIARES|VESICAL|PROSTATA|PELVICO|COLEDOCO|ENEMA|TRANSITO|TUBO DIGESTIVO|ESOFAGOGRAMA/;

/** Prefijo de código por categoría (mockup const PREF). */
export const PREF = { esp: "EE", rx: "RX", rm: "RM", tac: "TC", usg: "US" };

/** Duración estimada en minutos por categoría (mockup ternario en CATALOGO.push). */
export const DURACION_MIN_BY_CAT = { rm: 40, tac: 25, esp: 60, usg: 20, rx: 15 };

/**
 * Modalidad DICOM lógica (ImagingModalityType) por categoría — mapeo aprobado
 * por @Orq: rx→CR, tac→CT, rm→MR, usg→US, esp→XA (angiografía/procedimientos
 * intervencionistas, la mayoría de "esp" son arteriografías/biopsias guiadas).
 */
export const MODALITY_TYPE_BY_CAT = { esp: "XA", rx: "CR", rm: "MR", tac: "CT", usg: "US" };

/**
 * Construye el catálogo completo de 292 prestaciones aplicando las reglas de
 * derivación del mockup:
 *   - código = PREF[cat] + correlativo pad-3 (1-based dentro de la categoría).
 *   - contraste = RE_CONTRASTE.test(nombre).
 *   - ayuno = RE_AYUNO.test(nombre).
 *   - autorizacion = cat === 'esp' (todas las prestaciones de Estudios Especiales).
 *   - duracionMin = DURACION_MIN_BY_CAT[cat].
 *   - modalityType = MODALITY_TYPE_BY_CAT[cat].
 *
 * @returns {Array<{cat: string, code: string, name: string, displayOrder: number,
 *   contraste: boolean, ayuno: boolean, autorizacion: boolean, duracionMin: number,
 *   modalityType: string}>}
 */
export function construirCatalogo() {
  const items = [];
  for (const catId of Object.keys(RAW)) {
    RAW[catId].forEach((name, i) => {
      items.push({
        cat: catId,
        code: PREF[catId] + String(i + 1).padStart(3, "0"),
        name,
        displayOrder: i + 1,
        contraste: RE_CONTRASTE.test(name),
        ayuno: RE_AYUNO.test(name),
        autorizacion: catId === "esp",
        duracionMin: DURACION_MIN_BY_CAT[catId],
        modalityType: MODALITY_TYPE_BY_CAT[catId],
      });
    });
  }
  return items;
}
